#!/usr/bin/env python3
"""Generate the G1 policy configuration from the deployment bundle.

policies/fall_switch/plant.json and observation.json are the source of truth. This
script writes, from their exact values:

  policies/conventions.yaml           joint order, sorted by action_index
  policies/<policy>/policy.yaml       nominal gains, action scale, default pose
  policies/<policy>/observations.yaml the 98-wide observation, same for both policies

Run it from anywhere; it only uses the standard library:

  python3 scripts/gen_policy_from_plant.py          # write the files
  python3 scripts/gen_policy_from_plant.py --check  # fail if a file is out of date
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
POLICIES = ROOT / "policies"
BUNDLE = POLICIES / "fall_switch"
POLICY_NAMES = ("weak", "recovery_v0")
CONVENTION = "g1_fall_switch"

# Internal observation type and parameters for each term of observation.json, in order.
OBSERVATION_TERMS = {
    "base_ang_vel": ("base_ang_vel", {"sensor": "FloatingBase"}),
    "projected_gravity": ("projected_gravity", {"sensor": "FloatingBase"}),
    "command": ("command", {"size": 3}),
    "phase": ("phase", {"cos_first": "false", "command_deadzone": 0.1}),
    "joint_pos": ("joint_pos", {"joints": "all", "relative_to_default_pose": "true"}),
    "joint_vel": ("joint_vel", {"joints": "all", "relative_to_default_velocity": "true"}),
    "actions": ("last_action", {"joints": "all"}),
}
TERM_SIZES = {"base_ang_vel": 3, "projected_gravity": 3, "command": 3, "phase": 2}


def fail(message):
    sys.exit(f"gen_policy_from_plant: {message}")


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def load_bundle():
    manifest = json.loads((BUNDLE / "manifest.json").read_text())["files"]
    onnx = {f"{name}.onnx": POLICIES / name / f"{name}.onnx" for name in POLICY_NAMES}
    for name, expected in manifest.items():
        path = onnx.get(name, BUNDLE / name)
        if sha(path) != expected:
            fail(f"{path} does not match manifest.json ({sha(path)} != {expected})")
    return json.loads((BUNDLE / "plant.json").read_text()), json.loads((BUNDLE / "observation.json").read_text())


def check_plant(plant):
    joints = plant["joints"]
    if len(joints) != plant["action_dim"]:
        fail(f"{len(joints)} joints for action_dim {plant['action_dim']}")
    if sorted(j["action_index"] for j in joints) != list(range(plant["action_dim"])):
        fail("action_index is not a permutation of the action vector")
    for j in joints:
        if j["action_offset"] != j["default_pos"]:
            # The controller has a single q0, used for both the target and joint_pos.
            fail(f"{j['name']}: action_offset {j['action_offset']} != default_pos {j['default_pos']}")


def joint_map(joints, key, indent):
    pad = " " * indent
    return "".join(f"{pad}{j['name']}: {j[key]!r}\n" for j in joints)


def conventions_yaml(plant):
    ordered = sorted(plant["joints"], key=lambda j: j["action_index"])
    names = "".join(f"        {j['name']},\n" for j in ordered)
    return (
        "# Generated by scripts/gen_policy_from_plant.py from policies/fall_switch/plant.json. Do not edit.\n"
        "conventions:\n"
        f"  {CONVENTION}:\n"
        "    joint_groups:\n"
        "      # ONNX action and observation order: plant.json joints sorted by action_index.\n"
        "      all: [\n"
        f"{names}"
        "      ]\n"
    )


def policy_yaml(name, plant, observation):
    joints = plant["joints"]
    ranges = observation["command_ranges"]
    phase = next(t for t in observation["terms"] if t["name"] == "phase")
    return (
        "# Generated by scripts/gen_policy_from_plant.py from policies/fall_switch/plant.json. Do not edit.\n"
        f"name: {name}\n"
        f"onnx: {name}.onnx\n"
        "\n"
        "action:\n"
        "  joints: all\n"
        "  scale:\n"
        f"{joint_map(joints, 'action_scale', 4)}"
        "  q0:\n"
        f"{joint_map(joints, 'default_pos', 4)}"
        "\n"
        "control:\n"
        "  use_QP: true\n"
        f"  period_s: {plant['control_dt']!r}\n"
        "  pd_gains_ratio: 1.0\n"
        f"  phase_period: {float(phase['params']['period'])!r}\n"
        "  vel_cmd_speed:\n"
        f"    xy: {max(ranges['lin_vel_x'])!r}\n"
        f"    yaw: {max(ranges['ang_vel_z'])!r}\n"
        "  # Per-axis training range: the command seen by the policy is clamped to it.\n"
        "  command_ranges:\n"
        f"    lin_vel_x: {ranges['lin_vel_x']!r}\n"
        f"    lin_vel_y: {ranges['lin_vel_y']!r}\n"
        f"    ang_vel_z: {ranges['ang_vel_z']!r}\n"
        "  # Nominal gains, without the +/-10% training randomisation.\n"
        "  kp:\n"
        f"{joint_map(joints, 'kp', 4)}"
        "  kd:\n"
        f"{joint_map(joints, 'kd', 4)}"
    )


def observations_yaml(plant, observation):
    offset = 0
    lines = [
        "# Generated by scripts/gen_policy_from_plant.py from policies/fall_switch/observation.json. Do not edit.\n",
        f"training_convention: {CONVENTION}\n",
        "history_order_newest_first: true\n",
        "observation_source: realRobot\n",
        "\n",
        "observations:\n",
    ]
    for term in observation["terms"]:
        name = term["name"]
        if name not in OBSERVATION_TERMS:
            fail(f"unknown observation term '{name}'")
        begin, end = term["cols"]
        size = TERM_SIZES.get(name, plant["action_dim"])
        if begin != offset or end - begin != size:
            fail(f"term '{name}' has columns [{begin}, {end}], expected {size} values from {offset}")
        offset = end
        internal, parameters = OBSERVATION_TERMS[name]
        lines.append(f"  # columns [{begin}, {end})\n")
        lines.append(f"  - type: {internal}\n")
        lines.append(f"    name: {name}\n")
        lines.append("    parameters:\n")
        lines.extend(f"      {key}: {value}\n" for key, value in parameters.items())
    if offset != observation["dim"]:
        fail(f"terms cover {offset} columns, observation dim is {observation['dim']}")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a generated file is out of date")
    args = parser.parse_args()

    plant, observation = load_bundle()
    check_plant(plant)

    outputs = {POLICIES / "conventions.yaml": conventions_yaml(plant)}
    for name in POLICY_NAMES:
        outputs[POLICIES / name / "policy.yaml"] = policy_yaml(name, plant, observation)
        outputs[POLICIES / name / "observations.yaml"] = observations_yaml(plant, observation)

    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if args.check:
        if stale:
            fail("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        print("gen_policy_from_plant: up to date")
        return
    for path in stale:
        path.write_text(outputs[path])
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
